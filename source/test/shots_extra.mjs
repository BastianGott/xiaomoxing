import { chromium } from 'playwright';
const URL_ = new URL('../dist/xiaomoxing.html', import.meta.url).href;
const SHOTS = new URL('./shots/', import.meta.url).pathname;
const browser = await chromium.launch();
const page = await browser.newPage({ viewport: { width: 1280, height: 920 } });
const errors = [];
page.on('pageerror', e => errors.push(e.message));
await page.goto(URL_);
await page.evaluate(() => {
  localStorage.clear(); S = freshState(); S.welcomed = true;
  const now = Date.now(); CORE_ORDER.slice(0, 60).forEach(id => { S.cards[id] = { st: 2, s: 10, d: 5, last: now - 86400000 * 9, due: today(), reps: 3, lapses: 0 }; });
  save();
});
await page.reload();
await page.evaluate(() => { TTS.available = () => true; window.chooseMode = () => 'hear'; startEpoch(); });
await page.waitForTimeout(200);
await page.screenshot({ path: SHOTS + '60-word-hear.png' });
await page.keyboard.press('1'); await page.waitForTimeout(200);
await page.screenshot({ path: SHOTS + '61-word-hear-reveal.png' });
await page.keyboard.press('Escape'); await page.waitForTimeout(150); await page.keyboard.press('Enter');
await page.evaluate(() => gymModal()); await page.waitForTimeout(150);
await page.screenshot({ path: SHOTS + '62-gym-modal.png' });
await page.keyboard.press('Escape');
await page.click('.nav button[data-go="settings"]'); await page.waitForTimeout(150);
await page.screenshot({ path: SHOTS + '63-settings.png' });
await page.click('.nav button[data-go="lab"]'); await page.waitForTimeout(150);
await page.screenshot({ path: SHOTS + '64-lab.png' });
console.log('errors:', errors.length ? errors : 'none');
await browser.close();
